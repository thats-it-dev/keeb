import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

// Rebuilds src/lesson/corpus.ts from an MIT-licensed frequency dump.
// Usage: npx tsx scripts/make-corpus.ts [path-to-en_50k.txt]
// Source: github.com/hermitdave/FrequencyWords content/2016/en/en_50k.txt
import { FRAGMENTS, droppedGerund, isCleanWord } from "../src/lesson/clean.ts";
import { NAMES, NOT_WORDS } from "./blocklists.ts";

const MIN_COUNT = 1000; // drop rare forms and the typos that pollute the long tail
const MAX_WORDS = 4000; // keeps the bundle small; the tail barely matters for typing practice
const MAX_CANDIDATES = 6000; // how deep into the dump we look to reach MAX_WORDS
// Names and non-words are in scripts/blocklists.ts. Everything else the dump carries that has no business
// in a lesson — profanity, filler, contraction fragments — is in src/lesson/clean.ts, because the word
// generator has to apply the same rules to the words it invents.

const blocked = new Set<string>([...NAMES, ...NOT_WORDS]);
const file = process.argv[2] ?? "/tmp/en_50k.txt";
const rows = readFileSync(file, "utf8")
	.split("\n")
	.map((l) => l.trim())
	.filter(Boolean)
	.slice(0, MAX_CANDIDATES * 4)
	.map((l) => l.split(/\s+/));

const counts = new Map<string, number>();
for (const [word, count] of rows) {
	const w = word.toLowerCase();
	if (/^[a-z]+$/.test(w) && !counts.has(w) && Number(count) >= MIN_COUNT) counts.set(w, Number(count));
}
const candidates = [...counts.keys()];
const candidateSet = new Set(candidates);
const kept = new Set<string>();
const dropped = new Map<string, number>();
for (const w of candidates) {
	if (kept.size >= MAX_WORDS) break;
	const reason = rejectReason(w, blocked, candidateSet);
	if (reason) {
		dropped.set(reason, (dropped.get(reason) ?? 0) + 1);
		continue;
	}
	kept.add(w);
}

const picked = candidates.filter((w) => kept.has(w));

/** Why a word is not in the lesson, or "" when it is. */
function rejectReason(word: string, blockedWords: ReadonlySet<string>, all: ReadonlySet<string>): string {
	if (blockedWords.has(word)) return "name or non-word";
	if (droppedGerund(word, all)) return "g-dropped gerund";
	if (FRAGMENTS.has(word)) return "contraction fragment";
	if (!isCleanWord(word)) return "filler, profanity or not typeable";
	return "";
}
const lines: string[] = [];
for (let i = 0; i < picked.length; i += 16) {
	lines.push(`\t${picked.slice(i, i + 16).map((w) => `"${w}"`).join(", ")},`);
}
const body = `// English words, most frequent first. ${picked.length} entries.
// From a frequency dump of real spoken English, filtered to plain lowercase dictionary words of at least
// three characters (see SHORT_WORDS in clean.ts) with a vowel, and with profanity, filler, contraction
// fragments, names and non-words removed.
// Source: github.com/hermitdave/FrequencyWords (MIT). Deliberately not the keybr corpus, which
// ships with AGPL-3.0 code. Generated by scripts/make-corpus.ts; do not hand-edit.
export const WORDS: string[] = [
${lines.join("\n")}
];
`;
const out = new URL("../src/lesson/corpus.ts", import.meta.url);
mkdirSync(dirname(out.pathname), { recursive: true });
writeFileSync(out, body);
console.log(`wrote ${picked.length} words, ${Math.round(body.length / 1024)} KiB from ${candidates.length} candidates`);
for (const [reason, n] of [...dropped].sort((a, b) => b[1] - a[1])) console.log(`  dropped ${n}: ${reason}`);
