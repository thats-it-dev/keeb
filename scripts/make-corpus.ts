import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

// Rebuilds src/lesson/corpus.ts from an MIT-licensed frequency dump.
// Usage: npx tsx scripts/make-corpus.ts [path-to-en_50k.txt]
// Source: github.com/hermitdave/FrequencyWords content/2016/en/en_50k.txt
const MIN_COUNT = 500; // ignore hapax-like noise
const MAX_WORDS = 4000; // keeps the bundle small; the tail barely matters for typing practice

const file = process.argv[2] ?? "/tmp/en_50k.txt";
const rows = readFileSync(file, "utf8")
	.split("\n")
	.map((l) => l.trim())
	.filter(Boolean)
	.map((l) => l.split(/\s+/));

const seen = new Set<string>();
const picked: string[] = [];
for (const [word, count] of rows) {
	if (picked.length >= MAX_WORDS) break;
	const w = word.toLowerCase();
	if (w !== word || w.length < 2 || !/^[a-z]+$/.test(w) || seen.has(w)) continue;
	if (Number(count) < MIN_COUNT) continue;
	seen.add(w);
	picked.push(w);
}

const lines: string[] = [];
for (let i = 0; i < picked.length; i += 16) {
	lines.push(`\t${picked.slice(i, i + 16).map((w) => `"${w}"`).join(", ")},`);
}
const body = `// English words, most frequent first. ${picked.length} entries.
// Filtered to plain lowercase a-z words with at least ${MIN_COUNT} occurrences.
// Source: github.com/hermitdave/FrequencyWords (MIT). Deliberately not the keybr corpus, which
// ships with AGPL-3.0 code. Generated by scripts/make-corpus.ts; do not hand-edit.
export const WORDS: string[] = [
${lines.join("\n")}
];
`;
const out = new URL("../src/lesson/corpus.ts", import.meta.url);
mkdirSync(dirname(out.pathname), { recursive: true });
writeFileSync(out, body);
console.log(`wrote ${picked.length} words, ${Math.round(body.length / 1024)} KiB`);
